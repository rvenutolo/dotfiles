#!/usr/bin/env bash

set -Eeuo pipefail
IFS=$'\n\t'
trap 'echo "error: line ${LINENO} (exit $?): ${BASH_COMMAND}" >&2' ERR

# Rewrite the pre-commit-generated git hooks of this source repo so they find
# bash and pre-commit on PATH. A Nix-packaged pre-commit writes an absolute
# /nix/store shebang and `exec /nix/store/.../bin/pre-commit` line into each
# hook it installs, and every commit fails once a garbage collection removes
# that store path.
#
# Runs on every apply (run_ prefix, not run_onchange_): the hooks live outside
# the source state, and a plain `pre-commit install` brings the store paths back
# at any time, so no content hash of this script would notice.
#
# Self-contained on purpose: the same repair exists as pre-commit-hooks-repair
# in the personal scripts repo, but that repo is not present on every host.
#
# Every failure mode is non-fatal: a hook that cannot be rewritten logs a WARN.
# This script must never fail an apply over a git hook.

readonly MARKER='# File generated by pre-commit: https://pre-commit.com'
readonly SHEBANG_REGEX='^#!/nix/store/[^/]+/bin/(bash|sh)$'
readonly EXEC_REGEX='^exec /nix/store/[^/]+/bin/pre-commit( .*)$'
# The Nix hook template execs pre-commit directly and never reads this
# assignment, so a store path in it is inert.
readonly INERT_PREFIX='INSTALL_PYTHON='

# @description Log a timestamped message to stderr.
# @arg $1 level Severity label (INFO, WARN).
# @arg $2 message Text to log.
function log() {
  printf '[%s] %-5s %s\n' "$(date '+%Y-%m-%dT%H:%M:%S%z')" "$1" "$2" >&2
}
function log::info() { log 'INFO' "$*"; }
function log::warn() { log 'WARN' "$*"; }

# @description Rewrite one hook in place, keeping its mode. Leaves a file
# pre-commit did not generate (no marker on line 2), and a hook already free of
# store paths, untouched. A generated hook with any other store reference is
# left unmodified with a WARN.
# @arg $1 hook Path to a hook file.
# @exitcode 0 always.
function repair_hook() {
  local -r hook="$1"
  local -a lines=()
  mapfile -t lines < "${hook}"
  if ((${#lines[@]} < 2)) || [[ "${lines[1]}" != "${MARKER}" ]]; then
    return 0
  fi
  local -a rewritten=()
  local changed='false'
  local line
  for line in "${lines[@]}"; do
    if ((${#rewritten[@]} == 0)) && [[ "${line}" =~ ${SHEBANG_REGEX} ]]; then
      line="#!/usr/bin/env ${BASH_REMATCH[1]}"
      changed='true'
    elif [[ "${line}" =~ ${EXEC_REGEX} ]]; then
      line="exec pre-commit${BASH_REMATCH[1]}"
      changed='true'
    fi
    if [[ "${line}" == *'/nix/store/'* && "${line}" != "${INERT_PREFIX}"* ]]; then
      log::warn "${hook}: cannot rewrite store path in line: ${line}; left unchanged"
      return 0
    fi
    rewritten+=("${line}")
  done
  if [[ "${changed}" == 'true' ]]; then
    # Redirecting into the existing file keeps its executable mode.
    printf '%s\n' "${rewritten[@]}" > "${hook}"
    log::info "pre-commit hooks: rewrote ${hook} to resolve bash and pre-commit on PATH"
  fi
}

# @description Repair every hook file in a hooks directory, skipping samples.
# @arg $1 dir Hooks directory; a missing one is a no-op.
function repair_hooks_dir() {
  local -r dir="$1"
  local hook
  for hook in "${dir}"/*; do
    if [[ -f "${hook}" && "${hook}" != *.sample ]]; then
      repair_hook "${hook}"
    fi
  done
}

# @description Print a hook as a Nix-packaged pre-commit generates it.
# Fixture text only: the self-test never executes a hook.
# @arg $1 shell Basename of the shebang interpreter.
function fixture_hook() {
  local -r shell="$1"
  # shellcheck disable=SC2016 # literal hook text: the $ expressions belong to the generated hook
  printf '%s\n' \
    "#!/nix/store/aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa-bash-5.3p20/bin/${shell}" \
    "${MARKER}" \
    '# ID: 138fd403232d2ddd5efb44317e38bf03' \
    'INSTALL_PYTHON=/nix/store/bbbbbbbbbbbbbbbbbbbbbbbbbbbbbbbb-python3/bin/python3' \
    'ARGS=(hook-impl --config=.pre-commit-config.yaml --hook-type=pre-commit)' \
    'exec /nix/store/cccccccccccccccccccccccccccccccc-pre-commit-4.7.0/bin/pre-commit "${ARGS[@]}"'
}

# @description Record one self-test result.
# @arg $1 desc Case description.
# @arg $2 ok "true" if the case passed.
function check() {
  if [[ "$2" == 'true' ]]; then
    printf 'ok   %s\n' "$1"
  else
    printf 'FAIL %s\n' "$1"
    failures=$((failures + 1))
  fi
}

# @description Run the built-in test suite in a temp dir. No real hook is touched.
# @exitcode 0 if every case passes, 1 otherwise.
function self_test() {
  failures=0
  local root
  root="$(mktemp --directory)"
  # Backups live beside, not inside, the scanned dir, or they would be repaired too.
  local -r dir="${root}/hooks"
  local -r bak="${root}/bak"
  mkdir --parents -- "${dir}" "${bak}"
  local result

  fixture_hook 'bash' > "${dir}/pre-commit"
  chmod 0755 "${dir}/pre-commit"
  fixture_hook 'sh' > "${dir}/commit-msg"
  printf '#!/nix/store/dddd-bash/bin/bash\necho PAYLOAD_RAN\n' > "${dir}/pre-push"
  fixture_hook 'bash' > "${dir}/pre-rebase.sample"
  { fixture_hook 'bash' && printf 'echo /nix/store/eeee-unknown\n'; } > "${dir}/post-merge"
  : > "${dir}/empty"
  cp "${dir}/pre-push" "${bak}/pre-push"
  cp "${dir}/pre-rebase.sample" "${bak}/pre-rebase.sample"
  cp "${dir}/post-merge" "${bak}/post-merge"

  result="$(repair_hooks_dir "${dir}" 2>&1)"

  check 'bash shebang rewritten' \
    "$([[ "$(head --lines=1 "${dir}/pre-commit")" == '#!/usr/bin/env bash' ]] && echo true)"
  check 'sh shebang rewritten' \
    "$([[ "$(head --lines=1 "${dir}/commit-msg")" == '#!/usr/bin/env sh' ]] && echo true)"
  # shellcheck disable=SC2016 # literal hook text
  check 'exec line resolves pre-commit on PATH' \
    "$([[ "$(tail --lines=1 "${dir}/pre-commit")" == 'exec pre-commit "${ARGS[@]}"' ]] && echo true)"
  check 'inert INSTALL_PYTHON line kept' \
    "$(grep --quiet '^INSTALL_PYTHON=/nix/store/' "${dir}/pre-commit" && echo true)"
  check 'no other store path left' \
    "$(grep --invert-match '^INSTALL_PYTHON=' "${dir}/pre-commit" | grep --quiet '/nix/store/' || echo true)"
  check 'mode kept' "$([[ "$(stat --format='%a' "${dir}/pre-commit")" == '755' ]] && echo true)"
  check 'foreign hook untouched' "$(cmp --quiet "${bak}/pre-push" "${dir}/pre-push" && echo true)"
  check 'sample untouched' "$(cmp --quiet "${bak}/pre-rebase.sample" "${dir}/pre-rebase.sample" && echo true)"
  check 'unknown store reference left unchanged' \
    "$(cmp --quiet "${bak}/post-merge" "${dir}/post-merge" && echo true)"
  check 'unknown store reference warned' \
    "$([[ "${result}" == *'post-merge: cannot rewrite store path'* ]] && echo true)"
  check 'rewrite logged' "$([[ "${result}" == *"rewrote ${dir}/pre-commit"* ]] && echo true)"

  cp "${dir}/pre-commit" "${bak}/pre-commit"
  result="$(repair_hooks_dir "${dir}" 2>&1)"
  check 'second run leaves a repaired hook unchanged' \
    "$(cmp --quiet "${bak}/pre-commit" "${dir}/pre-commit" && echo true)"
  check 'second run logs no rewrite' "$([[ "${result}" != *'rewrote'* ]] && echo true)"

  check 'missing hooks dir is a no-op' "$(repair_hooks_dir "${dir}/no-such-dir" && echo true)"

  rm --recursive --force -- "${root:?}"
  if ((failures > 0)); then
    printf '\n%d case(s) failed\n' "${failures}"
    return 1
  fi
  printf '\nall cases passed\n'
}

function main() {
  if [[ "${1:-}" == '--self-test' ]]; then
    self_test
    exit $?
  fi
  local -r source_dir="${CHEZMOI_SOURCE_DIR:-}"
  if [[ -z "${source_dir}" ]] || ! command -v 'git' > /dev/null 2>&1; then
    log::warn 'pre-commit hooks: CHEZMOI_SOURCE_DIR unset or git missing; skipping'
    exit 0
  fi
  local hooks_dir
  if ! hooks_dir="$(git -C "${source_dir}" rev-parse --path-format=absolute --git-path hooks 2> /dev/null)"; then # -C: no long-form equivalent
    log::warn "pre-commit hooks: ${source_dir} is not a git repo; skipping"
    exit 0
  fi
  repair_hooks_dir "${hooks_dir}"
}

main "$@"
